"""Dataset audit CLI: builds the manifest, assigns folds, prints a summary
and writes it to the datasheet. Run after downloading a dataset into
data/raw/ per data/README.md.

    python -m training.audit_data --config configs/data.yaml
"""

from __future__ import annotations

import argparse
import random
from pathlib import Path

import numpy as np
import pandas as pd
import yaml

from training.data import assign_folds, discover_images, save_folds_csv, summarize

FAST_SAMPLE_PER_GROUP = 5


def set_seed(seed: int) -> None:
    random.seed(seed)
    np.random.seed(seed)


def load_config(config_path: str | Path) -> dict:
    with open(config_path, encoding="utf-8") as handle:
        return yaml.safe_load(handle)


def sample_for_fast_mode(manifest: pd.DataFrame, seed: int) -> pd.DataFrame:
    """Keep a small, class-balanced sample per dataset/kind/label group, so
    --fast gives a quick smoke check instead of scanning a full dataset."""
    def take_sample(group: pd.DataFrame) -> pd.DataFrame:
        return group.sample(min(len(group), FAST_SAMPLE_PER_GROUP), random_state=seed)

    return (
        manifest.groupby(["dataset", "kind", "label"], group_keys=False)
        .apply(take_sample)
        .reset_index(drop=True)
    )


def render_datasheet_markdown(summary: dict, fold_method: str, n_folds: int, seed: int) -> str:
    lines = [
        "# Datasheet",
        "",
        "Generated by `training/audit_data.py`. Do not hand-edit; rerun the",
        "script after the dataset changes.",
        "",
        f"- Total images: {summary['total_images']}",
        f"- Fold assignment method: `{fold_method}`",
        f"- Folds: {n_folds}, seed: {seed}",
        "",
    ]
    if fold_method == "grouped_by_image_hash_fallback":
        lines += [
            "## Leakage risk: no subject IDs",
            "",
            "This dataset has no usable subject ID column, so folds are",
            "grouped by perceptual image hash instead of by subject. This",
            "only prevents duplicate or near-duplicate images from splitting",
            "across train and test; it does not prevent the same person's",
            "other, non-duplicate drawings from appearing in both a training",
            "and a test fold. Treat any reported metrics on this data as",
            "optimistic relative to a true subject-held-out split. Prefer a",
            "dataset with subject IDs (HandPD/NewHandPD, PaHaW) when one is",
            "available; see data/README.md.",
            "",
        ]
    else:
        lines += [
            "## Leakage control: grouped by subject ID",
            "",
            "Folds are grouped by subject_id, so no subject appears in both",
            "a training and a test fold.",
            "",
        ]
    lines += [
        "## Counts by drawing kind and label",
        "",
        "| kind/label | count |",
        "|---|---|",
    ]
    for key, count in sorted(summary["counts_by_kind_label"].items()):
        lines.append(f"| {key} | {count} |")
    lines += [
        "",
        "## Counts by dataset",
        "",
        "| dataset | count |",
        "|---|---|",
    ]
    for key, count in sorted(summary["counts_by_dataset"].items()):
        lines.append(f"| {key} | {count} |")
    lines += [
        "",
        "## Image sizes observed",
        "",
        ", ".join(f"{w}x{h}" for w, h in summary["image_sizes"]) or "none",
        "",
        "## Duplicates",
        "",
        f"- Duplicate groups (same perceptual hash): {summary['duplicate_group_count']}",
        f"- Images involved in a duplicate group: {summary['duplicate_image_count']}",
        "",
        "## Subject IDs",
        "",
        f"- Available and usable: {summary['subject_ids_available']}",
        "",
    ]
    return "\n".join(lines)


def run_audit(
    raw_dir: str | Path,
    subject_id_regex: str | None,
    n_folds: int,
    seed: int,
    phash_size: int,
    fast: bool,
) -> tuple[pd.DataFrame, dict, str]:
    manifest = discover_images(raw_dir, subject_id_regex=subject_id_regex, phash_size=phash_size)
    if fast:
        manifest = sample_for_fast_mode(manifest, seed)
    folded = assign_folds(manifest, n_folds=n_folds, seed=seed)
    summary = summarize(folded)
    fold_method = folded.attrs.get("fold_method", "unknown")
    return folded, summary, fold_method


def main() -> None:
    parser = argparse.ArgumentParser(description="Audit data/raw/ and assign leakage-aware folds.")
    parser.add_argument("--config", default="configs/data.yaml")
    parser.add_argument("--seed", type=int, default=None)
    parser.add_argument(
        "--fast", action="store_true", help="sample a small subset for a quick check"
    )
    parser.add_argument("--raw-dir", default=None, help="override raw_dir from the config")
    parser.add_argument("--out", default=None, help="override datasheet_path from the config")
    parser.add_argument("--folds-out", default=None, help="override folds_path from the config")
    args = parser.parse_args()

    config = load_config(args.config)
    seed = args.seed if args.seed is not None else config["seed"]
    set_seed(seed)
    raw_dir = args.raw_dir or config["raw_dir"]
    datasheet_path = args.out or config["datasheet_path"]
    folds_path = args.folds_out or config["folds_path"]

    folded, summary, fold_method = run_audit(
        raw_dir=raw_dir,
        subject_id_regex=config.get("subject_id_regex"),
        n_folds=config["n_folds"],
        seed=seed,
        phash_size=config.get("phash_size", 8),
        fast=args.fast,
    )

    print(f"Total images: {summary['total_images']}")
    print(f"Fold method: {fold_method}")
    print("Counts by kind/label:")
    for key, count in sorted(summary["counts_by_kind_label"].items()):
        print(f"  {key}: {count}")
    print("Counts by dataset:")
    for key, count in sorted(summary["counts_by_dataset"].items()):
        print(f"  {key}: {count}")
    print(f"Image sizes observed: {summary['image_sizes']}")
    print(
        f"Duplicate groups: {summary['duplicate_group_count']} "
        f"({summary['duplicate_image_count']} images)"
    )
    print(f"Subject IDs available and usable: {summary['subject_ids_available']}")

    save_folds_csv(folded, folds_path)
    markdown = render_datasheet_markdown(summary, fold_method, config["n_folds"], seed)
    Path(datasheet_path).write_text(markdown, encoding="utf-8")
    print(f"Wrote folds to {folds_path} and datasheet to {datasheet_path}")


if __name__ == "__main__":
    main()
